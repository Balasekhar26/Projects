#!/usr/bin/env python
"""Success Rate Dashboard — Kattappa M38.

Reads ``evaluation/canary_history.jsonl`` and renders a Markdown scorecard
to stdout and ``evaluation/DASHBOARD.md``.

Usage::

    python evaluation/run_dashboard.py
    python evaluation/run_dashboard.py --last 5   # show last 5 runs only
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

EVAL_DIR = Path(__file__).parent
HISTORY_PATH = EVAL_DIR / "canary_history.jsonl"
DASHBOARD_PATH = EVAL_DIR / "DASHBOARD.md"


def _trend_arrow(current: float, previous: float | None) -> str:
    if previous is None:
        return "—"
    if current > previous:
        return f"↑ (+{current - previous:.1f}%)"
    if current < previous:
        return f"↓ ({current - previous:.1f}%)"
    return "→ (=)"


def _score_emoji(rate: float) -> str:
    if rate >= 90:
        return "🟢"
    if rate >= 75:
        return "🟡"
    return "🔴"


def load_history(last_n: int | None = None) -> list[dict]:
    if not HISTORY_PATH.exists():
        return []
    entries = []
    for line in HISTORY_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    if last_n:
        entries = entries[-last_n:]
    return entries


def build_dashboard(entries: list[dict]) -> str:
    lines: list[str] = []
    lines.append("# Kattappa Success Rate Dashboard")
    lines.append("")
    lines.append("> Generated by `evaluation/run_dashboard.py`")
    lines.append("")

    if not entries:
        lines.append("> [!WARNING]")
        lines.append("> No evaluation runs found in `canary_history.jsonl`.")
        lines.append("> Run `python evaluation/run_manual_evals.py --canary` to create the first entry.")
        return "\n".join(lines)

    # Summary table
    lines.append("## Run History")
    lines.append("")
    lines.append("| # | Date | Label | Passed | Failed | Rate | Trend |")
    lines.append("|---|---|---|---|---|---|---|")

    prev_rate: float | None = None
    for i, entry in enumerate(entries, 1):
        ts = entry.get("timestamp", "unknown")
        label = entry.get("run_label", "ALL TASKS")
        passed = entry.get("passed", 0)
        failed = entry.get("failed", 0)
        total = entry.get("total_tasks", passed + failed)
        rate = entry.get("success_rate", 0.0)
        emoji = _score_emoji(rate)
        trend = _trend_arrow(rate, prev_rate)
        lines.append(
            f"| {i} | {ts[:10]} | {label} | {passed}/{total} | {failed} | {emoji} {rate:.1f}% | {trend} |"
        )
        prev_rate = rate

    # Latest run details
    latest = entries[-1]
    latest_rate = latest.get("success_rate", 0.0)
    lines.append("")
    lines.append("## Latest Run")
    lines.append("")
    lines.append(f"- **Date**: {latest.get('timestamp', 'unknown')[:19].replace('T', ' ')} UTC")
    lines.append(f"- **Label**: {latest.get('run_label', 'ALL TASKS')}")
    lines.append(f"- **Score**: {latest.get('passed', 0)}/{latest.get('total_tasks', 0)} tasks")
    lines.append(f"- **Rate**: {latest_rate:.1f}%")
    lines.append("")

    # Target thresholds
    lines.append("## Target Thresholds")
    lines.append("")
    lines.append("| Threshold | Target | Current | Status |")
    lines.append("|---|---|---|---|")
    thresholds = [
        ("Canary 50 pass rate", 90.0, latest_rate),
        ("Failure-free rate",   100.0, 100.0 - (latest.get("failed", 0) / max(latest.get("total_tasks", 1), 1) * 100)),
    ]
    for name, target, current in thresholds:
        status = "✅ Met" if current >= target else f"❌ Gap: {target - current:.1f}%"
        lines.append(f"| {name} | ≥ {target:.0f}% | {current:.1f}% | {status} |")

    lines.append("")
    lines.append("---")
    lines.append("*Run `python evaluation/run_manual_evals.py --canary` to add a new entry.*")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Kattappa Success Rate Dashboard")
    parser.add_argument("--last", type=int, default=None,
                        help="Show only the last N runs.")
    args = parser.parse_args()

    entries = load_history(last_n=args.last)
    dashboard = build_dashboard(entries)

    DASHBOARD_PATH.write_text(dashboard, encoding="utf-8")
    print(dashboard)
    print(f"\nSaved dashboard to: {DASHBOARD_PATH}")

    if not entries:
        sys.exit(1)


if __name__ == "__main__":
    main()
